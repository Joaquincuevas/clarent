"""Regenerate docs/demo/ach.cast and docs/demo/ach.gif: `clarent ach` working through the flaky-test example.

    python docs/demo/make_ach_gif.py              # run the real commands, write ach.cast, render ach.gif
    python docs/demo/make_ach_gif.py --cast-only  # write ach.cast only (no renderer needed)

What is real and what is staged
  * Every line of command output is captured by running `python -m clarent ...` on the shipped example.
  * Only the keystrokes (typing speed), pauses, the shell prompt and the bold on '#' headings are staged.
  * The first command is shown with `| head -22` and its output is cut to 22 lines; the full report is in
    docs/demo/ach-score.md (regenerated by tools/gen_demo.py, which CI checks).

Rendering needs `agg` (https://github.com/asciinema/agg/releases, v1.9.0 tested): put it on PATH or set AGG=/path/to/agg.
The .cast is asciicast v2, so it can also be played with `asciinema play docs/demo/ach.cast`.
The GIF has to stay under 5 MB; this script fails if it does not.
"""
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "demo"
EXAMPLE = "methods/ach/examples/flaky-test.json"
ENV = {**os.environ, "PYTHONPATH": str(ROOT / "src"), "PYTHONIOENCODING": "utf-8", "CLARENT_LANG": "en"}

TYPE_DELAY = 0.045      # seconds per typed character
LINE_DELAY = 0.07       # seconds per line of output
HEAD_LINES = 22
PROMPT = "\x1b[1;32m$\x1b[0m "
MAX_GIF_BYTES = 5 * 1024 * 1024


def run(*args):
    r = subprocess.run([sys.executable, "-m", "clarent", *args], cwd=ROOT, env=ENV, capture_output=True,
                       text=True, encoding="utf-8")
    if r.returncode != 0:
        raise SystemExit(f"clarent {' '.join(args)} failed:\n{r.stderr}")
    return r.stdout.replace("\r\n", "\n").rstrip("\n").split("\n")


class Cast:
    def __init__(self):
        self.t, self.events = 0.0, []

    def out(self, data, dt=0.0):
        self.t += dt
        self.events.append([round(self.t, 3), "o", data])

    def pause(self, seconds):
        self.t += seconds

    def command(self, text):
        self.out(PROMPT)
        for ch in text:
            self.out(ch, TYPE_DELAY)
        self.out("\r\n", 0.35)

    def lines(self, lines):
        for ln in lines:
            styled = f"\x1b[1m{ln}\x1b[0m" if ln.startswith("#") else ln
            self.out(styled + "\r\n", LINE_DELAY)

    def clear(self):
        self.out("\x1b[2J\x1b[H")


def build():
    score = run("ach", "score", EXAMPLE)[:HEAD_LINES]
    nxt = run("ach", "next", EXAMPLE)
    cols = max(100, max(len(x) for x in score + nxt) + 2)
    cast = Cast()
    cast.pause(0.6)
    cast.command(f"clarent ach score {EXAMPLE} | head -{HEAD_LINES}")
    cast.lines(score)
    cast.pause(7.0)
    cast.clear()
    cast.pause(0.3)
    cast.command(f"clarent ach next {EXAMPLE}")
    cast.lines(nxt)
    cast.pause(6.0)
    header = {"version": 2, "width": cols, "height": HEAD_LINES + 4, "title": "clarent ach: flaky-test example",
              "env": {"TERM": "xterm-256color", "SHELL": "/bin/bash"}}
    return header, cast


def main():
    header, cast = build()
    path = OUT / "ach.cast"
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(json.dumps(header) + "\n")
        for ev in cast.events:
            f.write(json.dumps(ev, ensure_ascii=False) + "\n")
    print(f"wrote {path.relative_to(ROOT)} ({cast.t:.1f} s, {header['width']}x{header['height']})")
    if "--cast-only" in sys.argv[1:]:
        return
    agg = os.environ.get("AGG") or shutil.which("agg")
    if not agg:
        raise SystemExit("agg not found: install it from https://github.com/asciinema/agg/releases or set AGG=<path>")
    gif = OUT / "ach.gif"
    subprocess.run([agg, "--font-family", "Cascadia Mono,Consolas,DejaVu Sans Mono", "--font-size", "16", "--theme", "dracula", "--idle-time-limit", "8", "--last-frame-duration", "2",
                    str(path), str(gif)], check=True)
    size = gif.stat().st_size
    print(f"wrote {gif.relative_to(ROOT)} ({size / 1024:.0f} KiB)")
    if size >= MAX_GIF_BYTES:
        raise SystemExit("ach.gif is 5 MB or larger: shorten the recording or lower the font size")


if __name__ == "__main__":
    main()
