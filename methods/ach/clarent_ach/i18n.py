def set_lang(lang: str) -> None:
    global _LANG
    if lang not in M:
        raise ValueError(f"unsupported language {lang!r}; use one of {sorted(M)}")
    _LANG = lang


def get_lang() -> str:
    return _LANG


def t(key: str, **kw) -> str:
    s = M[_LANG][key]
    return s.format(**kw) if kw else s
